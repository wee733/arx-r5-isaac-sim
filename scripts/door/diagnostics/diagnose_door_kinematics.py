"""CPU-only FK/IK screening of door stages and prospective expert parameters.

No simulator, GPU planner, collision bypass, altered joint limits or recording
is involved. A solved IK target is only a geometric candidate for real replay.
A failed bounded search does not prove global unreachability. Free-space paths
are regenerated by cuMotion, so their recorded intermediate frames are omitted.
"""

import argparse
import json
from pathlib import Path
import sys
import time

import h5py
import numpy as np
from scipy.optimize import least_squares
from scipy.spatial.transform import Rotation

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from arx_door.kinematics import ArmKinematics  # noqa: E402
from arx_door.scene.workcell import sample_base_pose  # noqa: E402
from arx_door.runtime import arx_description_dir  # noqa: E402


def base_for_angle(metadata, angle):
    scene = metadata['scene_placement']
    options = scene['config']
    placement = sample_base_pose(scene['handle_world_xyz'], angle_deg=angle, **options)
    transform = np.eye(4)
    transform[:3, 3] = placement.position
    transform[:3, :3] = Rotation.from_quat(placement.quaternion_xyzw).as_matrix()
    return transform


def solve(kin, target, seed, attempts):
    started = time.monotonic()
    try:
        q = kin.ik(target, seed, attempts=attempts)
        actual = kin.fk(q)
        result = {
            'solved': True, 'joints': q.tolist(),
            'position_error_m': float(np.linalg.norm(actual[:3, 3] - target[:3, 3])),
            'rotation_error_rad': float(np.linalg.norm(Rotation.from_matrix(target[:3, :3].T @ actual[:3, :3]).as_rotvec())),
            'minimum_joint_limit_margin_rad': float(np.minimum(q - kin.lower, kin.upper - q).min()),
        }
    except ValueError as error:
        q = np.asarray(seed)
        result = {'solved': False, 'reason': str(error)}
    result['wall_s'] = time.monotonic() - started
    return result, q


def bounded_fit_diagnostic(kin, target, seed):
    """Expose which original bounds constrain the local best-fit failure."""
    def residual(q):
        actual = kin.fk(q)
        return np.r_[10 * (actual[:3, 3] - target[:3, 3]),
                     Rotation.from_matrix(target[:3, :3].T @ actual[:3, :3]).as_rotvec()]
    fit = least_squares(residual, np.clip(seed, kin.lower, kin.upper),
                        bounds=(kin.lower, kin.upper), max_nfev=150)
    margins = np.minimum(fit.x - kin.lower, kin.upper - fit.x)
    return {
        'diagnostic_only': True, 'original_limits_preserved': True,
        'best_local_joints': fit.x.tolist(), 'joint_limit_margins_rad': margins.tolist(),
        'saturated_joints': [f'joint{index + 1}' for index in np.flatnonzero(margins < 1e-5)],
        'position_error_m': float(np.linalg.norm(fit.fun[:3]) / 10),
        'rotation_error_rad': float(np.linalg.norm(fit.fun[3:])),
    }


def edge_target(panel, height, yaw, distance):
    target = np.eye(4)
    target[:3, :3] = panel[:3, :3] @ Rotation.from_euler('z', yaw, degrees=True).as_matrix()
    edge = (panel @ np.array([.743, .03475, height, 1]))[:3]
    target[:3, 3] = edge - distance * target[:3, 0]
    return target


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--seed-dir', type=Path, default=ROOT / 'generated/door_teaching/upright02/candidate_006')
    parser.add_argument('--seed-hdf5', type=Path, default=ROOT / 'generated/door_skillgen/seed/candidate_006.hdf5')
    parser.add_argument('--failed-trial', type=Path)
    parser.add_argument('--angles', type=float, nargs='+', default=[-30, 0, 30])
    parser.add_argument('--points-per-phase', type=int, default=3)
    parser.add_argument('--ik-attempts', type=int, default=12)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if args.points_per_phase < 1 or args.ik_attempts < 1:
        parser.error('points and IK attempts must be positive')
    metadata = json.loads((args.seed_dir / 'episode.json').read_text())
    with np.load(args.seed_dir / 'trajectory.npz', allow_pickle=False) as archive:
        actions, states, phases = archive['action'].copy(), archive['state'].copy(), archive['phase'].astype(str)
    kin = ArmKinematics(arx_description_dir() / 'urdf/r5a_cumotion.urdf')
    original_angle = metadata['scene_placement']['placement']['angle_deg']
    original_base = base_for_angle(metadata, original_angle)
    original_poses = np.asarray([original_base @ kin.fk(q[:6]) for q in actions])
    report = {'schema': 'arx-door-offline-kinematics-v1', 'physics_executed': False,
              'collision_checking_executed': False, 'ik_attempts': args.ik_attempts,
              'interpretation': 'IK screening only; original bounds/thresholds retained. Real experts require complete physical recording and visual review.',
              'seed_approval_status': metadata.get('quality_status'), 'angle_scans': [], 'expert_variants': []}
    current_panel = np.eye(4)
    current_panel[:3, 3] = [-.378, -.331, 0]
    current_panel[:3, :3] = Rotation.from_euler('z', -15, degrees=True).as_matrix()
    current_joints = states[0, :6]
    if args.failed_trial:
        failed_result = json.loads((args.failed_trial / 'result.json').read_text())
        path = Path(failed_result['artifacts']['hdf5'])
        if not path.is_file():
            path = args.failed_trial / path.name
        with h5py.File(path, 'r') as file:
            demo = file['data'][next(iter(file['data']))]
            current_panel = demo['obs/datagen_info/object_pose/panel'][-1].astype(float)
            current_joints = demo['obs/joint_pos'][-1, :6]
        start = int(np.flatnonzero(phases == 'approach_door_edge')[0])
        with h5py.File(args.seed_hdf5, 'r') as file:
            demo = file['data'][next(iter(file['data']))]
            source_panel = demo['obs/datagen_info/object_pose/panel'][start].astype(float)
            source_target = demo['obs/datagen_info/target_eef_pose/link6'][start].astype(float)
        target_world = current_panel @ np.linalg.inv(source_panel) @ source_target
        target = np.linalg.inv(original_base) @ target_world
        fitted, _ = solve(kin, target, current_joints, args.ik_attempts)
        report['refresh_diagnosis'] = {
            'failed_trial': str(args.failed_trial), 'last_pre_action_panel_rpy_deg': Rotation.from_matrix(current_panel[:3, :3]).as_euler('xyz', degrees=True).tolist(),
            'panel_orthogonality_error': float(np.linalg.norm(current_panel[:3, :3].T @ current_panel[:3, :3] - np.eye(3))),
            'source_edge_start_index': start, 'source_joint_limit_margin_rad': np.minimum(actions[start, :6] - kin.lower, kin.upper - actions[start, :6]).tolist(),
            'target_base': target.tolist(), 'ik': fitted,
            'bounded_fit': bounded_fit_diagnostic(kin, target, current_joints),
        }
        print(json.dumps({'refresh_diagnosis': report['refresh_diagnosis']}), flush=True)
    for angle in args.angles:
        inverse_base = np.linalg.inv(base_for_angle(metadata, angle))
        q = states[0, :6]
        rows = []
        for phase in dict.fromkeys(phases.tolist()):
            if phase.startswith('cumotion_'):
                continue
            indices = np.flatnonzero(phases == phase)
            selected = np.unique(np.linspace(indices[0], indices[-1], args.points_per_phase, dtype=int))
            for index in selected:
                result, q = solve(kin, inverse_base @ original_poses[index], q, args.ik_attempts)
                rows.append({'phase': phase, 'source_frame': int(index), **result})
        failed = sorted({row['phase'] for row in rows if not row['solved']})
        report['angle_scans'].append({'angle_deg': angle, 'sampled_targets': len(rows), 'failed_phases': failed, 'rows': rows})
        print(json.dumps({'angle_deg': angle, 'failed_phases': failed}), flush=True)
    variants = [('candidate_low_oblique', .96, 150, .18, 'candidate'),
                ('candidate_high_oblique', 1.06, 145, .18, 'candidate'),
                ('holdout_mid_oblique', .985, 155, .16, 'holdout')]
    for name, height, yaw, distance, split in variants:
        rows = []
        for door_angle in [12, 15, 20, 30]:
            panel = current_panel.copy()
            panel[:3, :3] = Rotation.from_euler('z', -door_angle, degrees=True).as_matrix()
            q = current_joints.copy()
            for label, tool_distance in [('pregrasp', distance), ('contact', .125)]:
                target = np.linalg.inv(original_base) @ edge_target(panel, height, yaw, tool_distance)
                result, q = solve(kin, target, q, args.ik_attempts)
                rows.append({'door_angle_deg': door_angle, 'stage': label, **result})
        variant = {'name': name, 'proposed_split': split, 'edge_height_m': height,
                   'edge_yaw_deg': yaw, 'edge_pregrasp_distance_m': distance,
                   'all_sampled_targets_solved': all(row['solved'] for row in rows), 'rows': rows,
                   'requires_independent_physical_recording': True}
        report['expert_variants'].append(variant)
        print(json.dumps({key: value for key, value in variant.items() if key != 'rows'}), flush=True)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2, allow_nan=False) + '\n')
    print(f'Report: {args.output}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
